/// Curated high-confidence standard English and technical lexicon.
///
/// Used by [DehyphenationService] to determine whether a word split across
/// lines by typesetting hyphenation forms a genuine unhyphenated English word
/// (e.g. `infor-` + `mation` -> `information`, `imple-` + `mentation` -> `implementation`).
