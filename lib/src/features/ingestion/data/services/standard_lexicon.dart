  const StandardLexicon._();

  /// Determines whether [word] is an authentic unhyphenated word.
  ///
  /// Performs an $O(1)$ set lookup against the core vocabulary, followed by
  /// morphological analysis for regular derivations and inflections:
  /// - Common derivational suffixes (`-tion`, `-ment`, `-able`, `-ance`, `-ence`, `-ity`, `-ness`, etc.)
  /// - Inflectional suffixes (`-s`, `-es`, `-ed`, `-ing`, `-ly`, `-er`, `-est`)
  /// - Common Latin/Greek scientific prefixes (`un-`, `re-`, `dis-`, `pre-`, `post-`, `sub-`, `multi-`, `auto-`, etc.)
  static bool contains(String word) {
    if (word.isEmpty) return false;
    final lower = word.toLowerCase();

    // 1. Exact match in core lexicon
    if (_words.contains(lower)) {
      return true;
    }

    // 2. Inflectional suffix normalization
    if (lower.length > 4) {
      if (lower.endsWith('ly') && _words.contains(lower.substring(0, lower.length - 2))) {
        return true;
      }
      if (lower.endsWith('ness') && _words.contains(lower.substring(0, lower.length - 4))) {
        return true;
      }
      if (lower.endsWith('able') && _words.contains(lower.substring(0, lower.length - 4))) {
        return true;
      }
      if (lower.endsWith('ible') && _words.contains(lower.substring(0, lower.length - 4))) {
        return true;
      }
      if (lower.endsWith('ment') && _words.contains(lower.substring(0, lower.length - 4))) {
        return true;
      }
      if (lower.endsWith('ization')) {
        final base = lower.substring(0, lower.length - 7);
        if (_words.contains(base) || _words.contains('${base}ize') || _words.contains('${base}al')) {
          return true;
        }
      }
      if (lower.endsWith('ation')) {
        final base = lower.substring(0, lower.length - 5);
        if (_words.contains(base) || _words.contains('${base}e') || _words.contains('${base}ate')) {
          return true;
        }
      }
      if (lower.endsWith('ity') && _words.contains(lower.substring(0, lower.length - 3))) {
        return true;
      }
      if (lower.endsWith('ing')) {
        final base = lower.substring(0, lower.length - 3);
        if (_words.contains(base) || _words.contains('${base}e')) {
          return true;
        }
        // Doubled consonant (e.g. running -> run, programming -> program)
        if (base.length > 2 && base[base.length - 1] == base[base.length - 2]) {
          if (_words.contains(base.substring(0, base.length - 1))) {
            return true;
          }
        }
      }
      if (lower.endsWith('ed')) {
        final base = lower.substring(0, lower.length - 2);
        if (_words.contains(base) || _words.contains('${base}e')) {
          return true;
        }
        if (base.length > 2 && base[base.length - 1] == base[base.length - 2]) {
          if (_words.contains(base.substring(0, base.length - 1))) {
            return true;
          }
        }
      }
      if (lower.endsWith('es')) {
        if (_words.contains(lower.substring(0, lower.length - 2))) {
          return true;
        }
      }
      if (lower.endsWith('s') && !lower.endsWith('ss')) {
        if (_words.contains(lower.substring(0, lower.length - 1))) {
          return true;
        }
      }
    }

    // 3. Productive derivational affixes for domain/scientific terms
    for (final prefix in _prefixes) {
      if (lower.startsWith(prefix) && lower.length > prefix.length + 3) {
        final remainder = lower.substring(prefix.length);
        if (_words.contains(remainder)) {
          return true;
        }
      }
    }

    return false;
  }

